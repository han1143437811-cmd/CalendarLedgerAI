"""Build the same small, original line icons for RemoteViews and the app."""
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
NAMESPACE = 'http://schemas.android.com/apk/res/android'
ET.register_namespace('android', NAMESPACE)
A = '{' + NAMESPACE + '}'
CLOUD = 'M6,18H18A4,4 0 0,0 18,10A6,6 0 0,0 7,8A5,5 0 0,0 6,18Z'
HIGH_CLOUD = 'M6,14H18A4,4 0 0,0 18,6A6,6 0 0,0 7,4A5,5 0 0,0 6,14Z'
ICONS = {
    'sun': [('sun', 'M12,7A5,5 0 1,0 12,17A5,5 0 1,0 12,7M12,2V4M12,20V22M2,12H4M20,12H22M4.9,4.9L6.3,6.3M17.7,17.7L19.1,19.1M4.9,19.1L6.3,17.7M17.7,6.3L19.1,4.9')],
    'partly': [('sun', 'M8,4A4,4 0 1,0 12,8M8,1V2M1,8H2M3,3L4,4M12,3L13,2'), ('cloud', 'M6,20H18A4,4 0 0,0 18,12A5.5,5.5 0 0,0 7.5,10A5,5 0 0,0 6,20Z')],
    'cloud': [('cloud', CLOUD)],
    'fog': [('cloud', HIGH_CLOUD), ('cloud', 'M3,18H21M5,22H19')],
    'rain': [('cloud', HIGH_CLOUD), ('rain', 'M8,17L6,21M13,17L11,21M18,17L16,21')],
    'snow': [('cloud', HIGH_CLOUD), ('rain', 'M8,16V22M5.5,17.5L10.5,20.5M5.5,20.5L10.5,17.5M17,16V22M14.5,17.5L19.5,20.5M14.5,20.5L19.5,17.5')],
    'storm': [('cloud', HIGH_CLOUD), ('sun', 'M12,15L8,19H12L10,23L17,17H13L15,15')],
}
for dark, colors in [(False, {'sun': '#A18D61', 'cloud': '#75887B', 'rain': '#6E8590'}),
                     (True, {'sun': '#D6C49D', 'cloud': '#C0CEC2', 'rain': '#B5CBD3'})]:
    for name, paths in ICONS.items():
        vector = ET.Element('vector', {A+'width': '24dp', A+'height': '24dp',
                                      A+'viewportWidth': '24', A+'viewportHeight': '24'})
        for color, path in paths:
            ET.SubElement(vector, 'path', {A+'pathData': path, A+'fillColor': '#00000000',
                         A+'strokeColor': colors[color], A+'strokeWidth': '1.8',
                         A+'strokeLineCap': 'round', A+'strokeLineJoin': 'round'})
        ET.indent(vector, space='    ')
        ET.ElementTree(vector).write(ROOT/'android/res/drawable'/('weather_'+name+('_dark' if dark else '')+'.xml'),
                                     encoding='utf-8', xml_declaration=True)
(ROOT/'prototype/weather-icons.mjs').write_text(
    '// Generated by tools/generate-weather-icons.py. Original app icon paths.\n'
    'export const weatherPaths = ' + json.dumps(ICONS, ensure_ascii=False, indent=2) + ';\n',
    encoding='utf-8')
print('WEATHER_ICONS_READY 14 Android vectors and 7 app icons')
